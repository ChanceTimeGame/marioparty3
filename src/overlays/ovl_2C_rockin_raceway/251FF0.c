typedef struct RRRecPlayer {
    /* 0x00 */ Vec trans;
    /* 0x0C */ Vec rot;
    /* 0x18 */ Vec scale;
    /* 0x24 */ f32 unk24;
    /* 0x28 */ f32 unk28;
} RRRecPlayer; /* size 0x2C */

typedef struct RRRecModel {
    /* 0x00 */ s32 unk0;
    /* 0x04 */ f32 unk4;
    /* 0x08 */ s32 unk8;
    /* 0x0C */ Vec pos;
    /* 0x18 */ Vec rot;
    /* 0x24 */ Vec scale;
} RRRecModel; /* size 0x30 */

typedef struct RRRecObj {
    /* 0x00 */ u16 unk0;
    /* 0x02 */ u16 unk2;
    /* 0x04 */ s32 unk4;
    /* 0x08 */ f32 unk8;
    /* 0x0C */ f32 unkC;
    /* 0x10 */ Vec pos;
    /* 0x1C */ Vec rot;
    /* 0x28 */ Vec scale;
} RRRecObj; /* size 0x34 */

/* One recorded frame of the race (30 kept in a ring). */
typedef struct RRRecFrame {
    /* 0x000 */ s32 unk0;
    /* 0x004 */ s32 unk4[4];
    /* 0x014 */ RRRecPlayer player[4];
    /* 0x0C4 */ RRRecModel model[12];
    /* 0x304 */ RRRecObj obj[16];
} RRRecFrame; /* size 0x644 */

/* The 0x30-byte entries of D_80111B5C_rockin_raceway. */
typedef struct RRObj {
    /* 0x00 */ u16 unk0;
    /* 0x02 */ s16 model;
    /* 0x04 */ f32 unk4;
    /* 0x08 */ f32 unk8;
    /* 0x0C */ char unkC[0x24];
} RRObj; /* size 0x30 */

/* What func_8010EC38_rockin_raceway unpacks from a player object's work[]. */
typedef struct RRPlayerWork {
    /* 0x00 */ char unk0[0x24];
    /* 0x24 */ f32 unk24;
    /* 0x28 */ char unk28[0x10];
    /* 0x38 */ f32 unk38;
} RRPlayerWork;

/* Pointers retail packs byte by byte into an object's work[]. */
typedef struct RRBytes {
    u32 a : 8;
    u32 b : 8;
    u32 c : 8;
    u32 d : 8;
} RRBytes;

typedef union RRPack {
    void* p;
    RRBytes b;
} RRPack;

