    f32 f;
    f32 t;
    f32 damp;
    f32 vel;
    f32 acc;
    f32 scale;
    u16 alpha;

    opSprBGDispOff(2);
    opSprBGDispOff(3);
    opSprBGDispOff(4);
    opSprBGDispOff(5);
    HuAudFXPlay(0x240);
    HuPrcSleep(16);
    for (i = 0; i < 40; i++) {
        HuPrcVSleep();
        f = 1.0f - i * (1.0f / 60.0f);
        t = f;
        if (f < 0.0f) {
            t = 0.0f;
        }
        opSprAlphaSet(0, (u8)(t * 255.0f));
    }
